#!/usr/bin/env python3
"""Habit and UI icons from Phosphor Icons 2.1.1 (MIT), the same set and keys as the Android app's
tools/gen_habit_icons.py. Writes template SVG imagesets into HabitDots/Assets.xcassets/Icons and
HabitKit's HabitIcons.swift (key list in picker order). Run from the repo root: python3 tools/gen_icons.py
"""
import io, json, pathlib, re, shutil, tarfile, urllib.request

VERSION = "2.1.1"
ICONS = """
drop drop-half coffee bowl-food fork-knife carrot avocado orange-slice egg pill syringe
barbell person-simple-run person-simple-walk person-simple-bike person-simple-swim person-simple-tai-chi
person-simple bicycle sneaker-move footprints mountains heartbeat heart tooth brain
moon moon-stars bed sun sun-horizon alarm timer hourglass
book-open books book-bookmark notebook note-pencil pencil-line graduation-cap translate lightbulb code laptop
hands-praying mosque hand-heart flower-lotus leaf plant potted-plant tree
guitar piano-keys music-notes microphone headphones paint-brush palette camera
broom washing-machine shower bathtub house shopping-cart
wallet piggy-bank coins scales
device-mobile-slash cigarette-slash prohibit wine beer-bottle game-controller television-simple
dog cat paw-print users chat-circle phone envelope gift
target calendar-check check-circle star sparkle trophy medal flag rocket-launch lightning smiley
""".split()
UI = {
    "fire-fill": "fill/fire-fill.svg", "gear-six": "regular/gear-six.svg", "dots-nine": "regular/dots-nine.svg",
    "chart-bar": "regular/chart-bar.svg", "tray": "regular/tray.svg", "x": "regular/x.svg",
    "caret-right": "regular/caret-right.svg", "caret-left": "regular/caret-left.svg", "caret-down": "regular/caret-down.svg",
    "check": "regular/check.svg", "palette-line": "regular/palette.svg", "archive": "regular/archive.svg",
    "database": "regular/database.svg", "cloud": "regular/cloud.svg", "sparkle-fill": "fill/sparkle-fill.svg",
    "lock-simple": "regular/lock-simple.svg", "share-network": "regular/share-network.svg",
    "note-pencil-line": "regular/note-pencil.svg", "calendar-check-line": "regular/calendar-check.svg",
    "pencil-simple": "regular/pencil-simple.svg", "dots-three": "regular/dots-three.svg", "trash": "regular/trash.svg",
    "plus": "regular/plus.svg", "arrow-left": "regular/arrow-left.svg", "arrows-clockwise": "regular/arrows-clockwise.svg",
    "bell": "regular/bell.svg", "calendar-blank": "regular/calendar-blank.svg", "paper-plane-right": "regular/paper-plane-right.svg",
    "trend-up": "regular/trend-up.svg", "trend-down": "regular/trend-down.svg", "minus": "regular/minus.svg",
}

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "Shared/Icons.xcassets/Icons"
tar = tarfile.open(fileobj=io.BytesIO(urllib.request.urlopen(f"https://registry.npmjs.org/@phosphor-icons/core/-/core-{VERSION}.tgz").read()))

def svg(path):
    src = tar.extractfile(f"package/assets/{path}").read().decode()
    return re.sub(r'fill="currentColor"', 'fill="#000000"', src).replace("<svg ", '<svg width="24" height="24" ', 1)

shutil.rmtree(out, ignore_errors=True)
out.mkdir(parents=True)
(out / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": True}}, indent=2))

def imageset(name, data):
    d = out / f"{name}.imageset"
    d.mkdir()
    (d / f"{name}.svg").write_text(data)
    (d / "Contents.json").write_text(json.dumps({
        "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
        "info": {"author": "xcode", "version": 1},
        "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
    }, indent=2))

for key in ICONS:
    imageset(key, svg(f"duotone/{key}-duotone.svg"))
for key, path in UI.items():
    imageset("ui-" + key, svg(path))

swift = root / "Packages/HabitKit/Sources/HabitDesign/HabitIcons.swift"
swift.write_text(
    "// Generated by tools/gen_icons.py from Phosphor Icons " + VERSION + " (MIT). Do not edit by hand.\n\n"
    "/// Habit icon keys (stored in `tracker.icon`), in picker order. Images live in the app's asset catalog as \"Icons/<key>\".\n"
    "public let habitIconKeys: [String] = [\n" + "".join(f'    "{k}",\n' for k in ICONS) + "]\n"
)
print(len(ICONS), "habit icons,", len(UI), "UI icons")
